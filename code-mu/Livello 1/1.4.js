// 1. Stampa nella console tutti i numeri interi da 1 a 100.
for (let i=1; i <= 100; i++) {
    console.log(i);
}


// 2. Stampa nella console tutti i numeri interi da -100 a 0.
for (let i=-100; i <= 0; i++) {
    console.log(i);
}


// 3. Stampa nella console tutti i numeri interi da 100 a 1.
for (let i=100; i >= 1; i--) {
    console.log(i);
}


// 4. Stampa nella console tutti i numeri pari nell'intervallo da 1 a 100.
for (let i = 2; i <= 100; i=i+2) {
    console.log(i);
}

// 5. Stampa nella console tutti i numeri divisibili per tre nell'intervallo da 1 a 100.
for (let i=3; i<=100; i=i+3) {
    console.log(i);
}